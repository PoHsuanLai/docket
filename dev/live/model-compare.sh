#!/usr/bin/env bash
# Plays the everyday flows against several cloud models and writes a comparison table, so the
# companion's planner model is picked by measurement (docs/live-eval.md, "Comparing models").
#
#   dev/live/model-compare.sh --keys-home DIR --models "cloud/<id> cloud/<id> ..." \
#       [--repeat N] [--flows "fact remember what-remember mail-find"] [--spend-cents N] \
#       [--helper cloud/<id>]
#
# For each model it writes an inferd config in the run's scratch directory (outside git) that pins
# the planner's tier (balanced) to that model and the helpers' tiers (fast: the policy writer and
# quick reviewer, which need structured output; best) to --helper (default
# cloud/gemini-3.8-flash), so only the planner differs between rows, then runs dev/live-smoke.sh --engine cloud for the flows
# --repeat times (default 3). The key never passes through this script: only --keys-home is
# forwarded, as live-smoke does. The table (model x flow, passes out of N, and the median length of
# the "fact" answer) goes to stdout and to <scratch>/comparison.md.
# The scratch directory holds traces, which contain prompts: delete it when done.
set -euo pipefail
root=$(cd "$(dirname "$0")/../.." && pwd)

keys=""
models=""
repeat=3
flows="fact remember what-remember mail-find"
spend=500
helper="cloud/gemini-3.8-flash"
usage() {
  echo "usage: model-compare.sh --keys-home DIR --models \"cloud/<id> ...\" [--repeat N] [--flows \"fact ...\"] [--spend-cents N] [--helper cloud/<id>]" >&2
  exit 2
}
while [ $# -gt 0 ]; do
  [ $# -ge 2 ] || usage
  case "$1" in
    --keys-home) keys=$2 ;;
    --models) models=$2 ;;
    --helper) helper=$2 ;;
    --repeat) repeat=$2 ;;
    --flows) flows=$2 ;;
    --spend-cents) spend=$2 ;;
    *) usage ;;
  esac
  shift 2
done
[ -n "$keys" ] && [ -n "$models" ] || usage
case "$keys" in /*) ;; *) echo "model-compare: --keys-home must be an absolute path" >&2; exit 2 ;; esac
case "$repeat" in ''|*[!0-9]*|0) echo "model-compare: --repeat takes a number of at least 1" >&2; exit 2 ;; esac
case "$spend" in ''|*[!0-9]*) echo "model-compare: --spend-cents takes a number" >&2; exit 2 ;; esac
for model in $models; do
  case "$model" in
    *[!A-Za-z0-9._/:-]*|'') echo "model-compare: odd model id: $model" >&2; exit 2 ;;
  esac
done

scratch=$(mktemp -d "${TMPDIR:-/tmp}/docket-compare.XXXXXX")
chmod 700 "$scratch"
echo "model-compare: scratch $scratch (traces hold prompts; delete it when done)" >&2
: >"$scratch/failures.tsv"

flow_args=()
for flow in $flows; do flow_args+=(--flow "$flow"); done

declare -A passes
declare -A lens
for model in $models; do
  slug=${model//[^A-Za-z0-9]/_}
  dir="$scratch/$slug"
  mkdir -p "$dir"
  cat >"$dir/inferd.toml" <<TOML
# Generated by model-compare.sh: the planner (balanced) is $model; the helpers are $helper.
[ai]
local_only = "off"

[ai.floor]
prompt = "anywhere"
mail = "anywhere"

[ai.model.text]
fast = "$helper"
balanced = "$model"
best = "$helper"

[ai.spend]
account_daily_cents = $spend
app_daily_cents = $spend
TOML
  echo "model-compare: $model" >&2
  rc=0
  LIVE_SCRATCH="$dir/live" "$root/dev/live-smoke.sh" --engine cloud \
    --inferd-config "$dir/inferd.toml" --keys-home "$keys" --repeat "$repeat" \
    "${flow_args[@]}" >"$dir/smoke.out" 2>"$dir/smoke.err" || rc=$?
  if [ "$rc" -ge 2 ]; then
    echo "model-compare: $model: the run could not start (exit $rc); see $dir/smoke.err" >&2
  fi
  key=""
  while IFS= read -r line; do
    case "$line" in
      PASS\ *|FAIL\ *)
        status=${line%% *}
        rest=${line#* }
        name=${rest%% *}
        trace=${line##*trace: }
        flow=${name%%.run*}
        key="$model|$flow"
        if [ "$status" = PASS ]; then
          passes[$key]=$(( ${passes[$key]:-0} + 1 ))
          key=""
        fi
        if [ "$flow" = fact ] && [ -f "$trace" ]; then
          n=$(sed -n 's/^answer chars: //p' "$trace" | head -n 1)
          [ -z "$n" ] || lens[$model]="${lens[$model]:-} $n"
        fi
        ;;
      "     ["*)
        if [ -n "$key" ]; then
          reason=${line#"${line%%[![:space:]]*}"}
          printf '%s\t%s\t%s\n' "${key%%|*}" "${key#*|}" "$reason" >>"$scratch/failures.tsv"
        fi
        ;;
    esac
  done <"$dir/smoke.out"
done

median() {
  if [ $# -eq 0 ]; then echo "-"; return; fi
  printf '%s\n' "$@" | sort -n | awk '{ a[NR] = $1 } END { print (NR % 2) ? a[(NR + 1) / 2] : int((a[NR / 2] + a[NR / 2 + 1]) / 2) }'
}

table="$scratch/comparison.md"
{
  echo "## Model comparison ($repeat run(s) per flow)"
  echo
  header="| model |"
  rule="|---|"
  for flow in $flows; do header+=" $flow |"; rule+="---|"; done
  echo "$header fact median chars |"
  echo "$rule---|"
  for model in $models; do
    row="| $model |"
    for flow in $flows; do
      k="$model|$flow"
      row+=" ${passes[$k]:-0}/$repeat |"
    done
    # shellcheck disable=SC2086
    echo "$row $(median ${lens[$model]:-}) |"
  done
  echo
  if [ -s "$scratch/failures.tsv" ]; then
    echo "### Failing expectations"
    echo
    awk -F'\t' '{ n[$1 "\t" $2 "\t" $3]++ }
      END { for (k in n) { split(k, p, "\t"); printf "- %s, %s (x%d): %s\n", p[1], p[2], n[k], p[3] } }' \
      "$scratch/failures.tsv" | sort
    echo
  fi
  echo "Scratch: $scratch (traces hold prompts; delete it with: rm -rf $scratch)"
} | tee "$table"
echo "model-compare: table written to $table" >&2
